# =====================================================================
# Consolidate-ZivoSql.ps1
#
# Builds 4 consolidated SQL files from YOUR 32 on-disk migration files,
# and quarantines the 5 dead ones.
#
# WHY THIS IS A SCRIPT AND NOT 4 READY-MADE FILES:
#   The master .txt dump is mojibake-corrupted (every RS symbol appears as
#   3 wrong characters, every emoji likewise). Rebuilding your migrations
#   from that dump would bake the corruption into product names, emojis
#   and frame-size strings. This script reads your REAL files off disk,
#   byte-for-byte, so nothing is re-encoded or guessed.
#
# IT DOES NOT TOUCH SUPABASE. It only reads/writes files in your repo.
#
# USAGE (from the repo root):
#   powershell -ExecutionPolicy Bypass -File .\Consolidate-ZivoSql.ps1
# =====================================================================

param(
  [string]$SqlDir  = ".\supabase",
  [string]$OutDir  = ".\supabase\consolidated",
  [string]$ArchDir = ".\supabase\_archive"
)

$ErrorActionPreference = "Stop"

# ---- Dead / fully-duplicated files. Moved to _archive, never run. ----
$Dead = @(
  "schema-sender-otp.sql",                          # header says: SUPERSEDED, do not run
  "schema-commercial-wording.sql",                  # replaced by schema-catalog-wording-FINAL.sql
  "schema-rename-digital-bday.sql",                 # replaced by schema-catalog-wording-FINAL.sql
  "schema-fix-orders-ref-column.sql",               # orders.ref already added inside schema.sql
  "schema-digital-studio-catalog-completeness.sql"  # duplicate of schema-voice-video-tribute.sql
)

# ---- Consolidation groups, in STRICT run order. ----
# Order matters in three places:
#   portrait-frames BEFORE frames-pricing  (else A4/A3 prices get wiped)
#   schema.sql      BEFORE fix-track-order-leak (else the leak returns)
#   group2          BEFORE 02_functions.sql (it reads gift_reactions)
$Groups = [ordered]@{
  "10_core.sql" = @(
    "schema.sql"
  )
  "20_features.sql" = @(
    "schema-group2.sql",
    "schema-group3.sql",
    "schema-friend-special-dates.sql",
    "schema-group4.sql",
    "schema-group4-part2.sql",
    "schema-group5.sql",
    "schema-care-package.sql",
    "schema-share-clip.sql",
    "schema-voice-video-tribute.sql",
    "schema-portrait-frames.sql",
    "schema-portrait-frames-v2.sql",
    "schema-gift-reveal-v2.sql",
    "schema-account-phone-verification.sql",
    "schema-sender-otp-msg91.sql",
    "schema-webhook-replay-protection.sql",
    "schema-scheduler-hardening.sql"
  )
  "30_fixes_and_pricing.sql" = @(
    "schema-fix-digital-sends-email.sql",
    "schema-fix-track-order-leak.sql",
    "schema-admin-order-delete.sql",
    "schema-admin-carepkg-visibility.sql",
    "schema-frames-pricing.sql",
    "schema-catalog-wording-FINAL.sql",
    "schema-promo-suri-and-addons.sql"
  )
  "40_columns_functions_indexes.sql" = @(
    "01_columns.sql",
    "02_functions.sql",
    "03_indexes.sql"
  )
}

if (-not (Test-Path $SqlDir)) { throw "SQL directory not found: $SqlDir" }
New-Item -ItemType Directory -Force -Path $OutDir  | Out-Null
New-Item -ItemType Directory -Force -Path $ArchDir | Out-Null

# ---- Coverage check: nothing on disk may be silently left behind. ----
$OnDisk    = Get-ChildItem -Path $SqlDir -Filter *.sql -File | Select-Object -ExpandProperty Name
$Grouped   = $Groups.Values | ForEach-Object { $_ }
$Accounted = @($Grouped) + @($Dead)
$Missing   = $OnDisk    | Where-Object { $Accounted -notcontains $_ }
$NotFound  = $Accounted | Where-Object { $OnDisk    -notcontains $_ }

Write-Host ("Found {0} .sql files on disk. Script accounts for {1}." -f $OnDisk.Count, $Accounted.Count)
if ($NotFound) { Write-Warning ("Listed but not on disk (skipped): " + ($NotFound -join ", ")) }
if ($Missing)  { Write-Warning ("On disk but NOT grouped - review manually: " + ($Missing -join ", ")) }

# ---- Build the 4 consolidated files. ----
# Read/write as raw UTF-8 with no BOM so byte content is preserved exactly.
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)

foreach ($outName in $Groups.Keys) {
  $sb = New-Object System.Text.StringBuilder
  [void]$sb.AppendLine("-- =====================================================================")
  [void]$sb.AppendLine("-- ZIVOGIFT consolidated migration: $outName")
  [void]$sb.AppendLine("-- Generated by Consolidate-ZivoSql.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm')")
  [void]$sb.AppendLine("--")
  [void]$sb.AppendLine("-- Run order for a FRESH database: 10 -> 20 -> 30 -> 40.")
  [void]$sb.AppendLine("-- On an EXISTING live database you do NOT need to run these at all;")
  [void]$sb.AppendLine("-- every file below has already been applied. Re-running would reset")
  [void]$sb.AppendLine("-- admin-edited prices (several use: on conflict do update set price).")
  [void]$sb.AppendLine("-- =====================================================================")
  [void]$sb.AppendLine("")

  $used = 0
  foreach ($src in $Groups[$outName]) {
    $path = Join-Path $SqlDir $src
    if (-not (Test-Path $path)) { Write-Warning "Skipping missing file: $src"; continue }
    $body = [System.IO.File]::ReadAllText($path)
    [void]$sb.AppendLine("-- ---------------------------------------------------------------------")
    [void]$sb.AppendLine("-- SOURCE: $src")
    [void]$sb.AppendLine("-- ---------------------------------------------------------------------")
    [void]$sb.AppendLine($body.TrimEnd())
    [void]$sb.AppendLine("")
    $used++
  }

  $outPath = Join-Path $OutDir $outName
  [System.IO.File]::WriteAllText($outPath, $sb.ToString(), $Utf8NoBom)
  Write-Host ("Wrote {0}  ({1} source files merged)" -f $outPath, $used)
}

# ---- Quarantine the dead files (moved, not deleted). ----
foreach ($d in $Dead) {
  $p = Join-Path $SqlDir $d
  if (Test-Path $p) {
    Move-Item -Path $p -Destination (Join-Path $ArchDir $d) -Force
    Write-Host "Archived $d"
  }
}

Write-Host ""
Write-Host "Done. Consolidated files are in $OutDir; 5 dead files archived in $ArchDir."
Write-Host "Nothing was executed against Supabase."
Write-Host ""
Write-Host "SANITY CHECK before you commit - the frame-size strings must stay ASCII:"
Write-Host "  Select-String -Path `"$OutDir\30_fixes_and_pricing.sql`" -Pattern 'A4 \(8x12 in\)'"
Write-Host "If that returns nothing, STOP - the encoding was mangled and you must not commit."
